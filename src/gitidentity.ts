// The one git identity every sandbox commit carries: the GitHub App's own bot user, so
// commits map to a real GitHub account (Vercel refuses PR deploys for an author email
// that matches no account). The numeric id is coach-aven[bot]'s user id.
export const GIT_NAME = 'coach-aven[bot]';
export const GIT_EMAIL = '271933357+coach-aven[bot]@users.noreply.github.com';

// Env prefix for the claude process. `git config --global` alone is not enough: the
// agent once committed with `git -c user.name="Claude" -c user.email=noreply@anthropic.com`
// (holidayshop-hsx 73af354, its CLI habit), and `-c` / a repo-local config both beat
// --global. GIT_AUTHOR_* / GIT_COMMITTER_* beat ANY user.name/user.email source, so
// every commit from the session and its subprocesses carries the bot identity.
// Only an explicit `--author` still wins — the system prompt forbids that.
export function gitIdentityEnv(): string {
  const name = `'${GIT_NAME}'`;
  const email = `'${GIT_EMAIL}'`;
  return (
    `GIT_AUTHOR_NAME=${name} GIT_AUTHOR_EMAIL=${email} ` +
    `GIT_COMMITTER_NAME=${name} GIT_COMMITTER_EMAIL=${email}`
  );
}

