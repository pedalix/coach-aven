// The one git identity every sandbox commit carries: the account the bot's GitHub credential
// acts as, so commits map to a real GitHub account (Vercel refuses PR deploys for an author
// email that matches no account) and to the account that pushed them. With a GitHub App that
// is the App's bot user, `<app-slug>[bot]`; with a personal token (GITHUB_TOKEN) the token's
// owner. The bot asks GitHub who it is when it first resolves a token (github.ts,
// ensureGitIdentity) — before any sandbox is seeded or any session starts — and keeps the
// answer for the life of the process. Until then, and with GITHUB_AUTH=none (nothing is ever
// pushed), the values below are the shared App's bot, coach-aven[bot], and its user id.
// GITHUB_BOT_LOGIN + GITHUB_BOT_USER_ID in the installation's .env name the account by hand
// and skip the question; both or neither.
export interface GitIdentity {
  /** The GitHub login: the commit author name, and the author of the pull requests the bot opens. */
  login: string;
  email: string;
}

/** GitHub's no-reply address for an account, by which a commit maps to it. */
export function identityOf(login: string, userId: string | number): GitIdentity {
  return { login, email: `${userId}+${login}@users.noreply.github.com` };
}

export const DEFAULT_GIT_IDENTITY: GitIdentity = identityOf('coach-aven[bot]', 271933357);

const LOGIN_RE = /^[A-Za-z0-9][A-Za-z0-9-]*(\[bot\])?$/;
const USER_ID_RE = /^[1-9][0-9]*$/;

/** An identity read from GitHub or from .env: refused unless it is a login and a numeric id —
 *  both are interpolated into sandbox shell commands. */
export function checkedIdentity(login: unknown, userId: unknown, source: string): GitIdentity {
  if (typeof login !== 'string' || !LOGIN_RE.test(login)) throw new Error(`${source}: not a GitHub login: ${String(login)}`);
  if (!USER_ID_RE.test(String(userId))) throw new Error(`${source}: not a numeric GitHub user id: ${String(userId)}`);
  return identityOf(login, String(userId));
}

/** The identity the installation's .env names, if it names one. Throws on half a pair or a bad value (at boot). */
export function gitIdentityOverride(env: Record<string, string | undefined>): GitIdentity | undefined {
  const login = env.GITHUB_BOT_LOGIN?.trim();
  const id = env.GITHUB_BOT_USER_ID?.trim();
  if (!login && !id) return undefined;
  if (!login || !id) throw new Error('GITHUB_BOT_LOGIN and GITHUB_BOT_USER_ID go together: set both or neither');
  return checkedIdentity(login, id, 'GITHUB_BOT_LOGIN / GITHUB_BOT_USER_ID');
}

// Live bindings: importers read the current value at each use, so a session spawned after the
// lookup carries the looked-up identity.
export let GIT_NAME = DEFAULT_GIT_IDENTITY.login;
export let GIT_EMAIL = DEFAULT_GIT_IDENTITY.email;

// Claude Code `attribution` setting (passed via --settings): replaces the CLI's default
// "Co-Authored-By: Claude …" commit trailer and "Generated with Claude Code" PR footer,
// so the credit on client repos is CoachAven's. Object form — older CLIs reject a bool.
const attribution = (email: string) => ({
  attribution: { commit: `Co-Authored-By: CoachAven <${email}>`, pr: '🤖 Generated by CoachAven' },
});
export let ATTRIBUTION_SETTINGS = attribution(GIT_EMAIL);

export function setGitIdentity(i: GitIdentity): void {
  GIT_NAME = i.login;
  GIT_EMAIL = i.email;
  ATTRIBUTION_SETTINGS = attribution(i.email);
}

// Env prefix for the claude process. `git config --global` alone is not enough: the
// agent once committed with `git -c user.name="Claude" -c user.email=noreply@anthropic.com`
// (holidayshop-hsx 73af354, its CLI habit), and `-c` / a repo-local config both beat
// --global. GIT_AUTHOR_* / GIT_COMMITTER_* beat ANY user.name/user.email source, so
// every commit from the session and its subprocesses carries the bot identity.
// Only an explicit `--author` still wins — the system prompt forbids that.
export function gitIdentityEnv(): string {
  const name = `'${GIT_NAME}'`;
  const email = `'${GIT_EMAIL}'`;
  return (
    `GIT_AUTHOR_NAME=${name} GIT_AUTHOR_EMAIL=${email} ` +
    `GIT_COMMITTER_NAME=${name} GIT_COMMITTER_EMAIL=${email}`
  );
}
